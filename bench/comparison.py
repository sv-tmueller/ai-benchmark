def _artifact_filename(prefix: str, model_key: str) -> str:
    """Build the expected artifact filename."""
    safe_prefix = prefix.replace("/", "_").strip("_")
    safe_mk = model_key.replace("/", "_").strip("_")
    return f"{safe_prefix}_{safe_mk}.html"


def write_game_comparison_html(
    results: list[SingleResult],
    artifacts_dir: Path,
    out_path: Path,
    model_keys: list[str] | None = None,
) -> Path:
    """Generate a self-contained HTML viewer with per-model tabs.

    Each tab hosts an ``<iframe>`` that loads the corresponding artifact
    HTML file (named ``PREFIX_MODELKEY.html``) from *artifacts_dir*.

    Parameters
    ----------
    results
        Flat list of :class:`SingleResult` objects.
    artifacts_dir
        Directory containing saved artifact ``.html`` files.
    out_path
        Destination ``.html`` file path.
    model_keys
        Optional whitelist of model keys to include.
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)
    artifacts_dir = Path(artifacts_dir)

    grouped = _group_by_prompt(results, model_keys)
    cols = _ordered_model_keys(grouped, model_keys)

    parts: list[str] = []

    parts.append("<!DOCTYPE html>")
    parts.append('<html lang="en"><head>')
    parts.append('<meta charset="utf-8"/>')
    parts.append('<meta name="viewport" content="width=device-width, initial-scale=1"/>')
    parts.append("<title>Game Comparison Viewer</title>")
    parts.append(_GAME_CSS)
    parts.append("</head><body>")

    parts.append("<header><h1>&#127918; Game Comparison Viewer</h1></header>")

    if not grouped or not cols:
        parts.append('<div class="missing">No results to display.</div>')
        parts.append("</body></html>")
        out_path.write_text("\n".join(parts))
        return out_path

    # Collect distinct prompts (sections) -------------------------------
    prompt_ids = list(grouped.keys())

    # Section selector (dropdown) + model tabs ---------------------------
    # Layout: outer section selector, inner model-tab bar, iframe pane area.

    parts.append('<nav class="tabs" id="section-tabs">')
    for idx, pid in enumerate(prompt_ids):
        sample = next(iter(grouped[pid].values()))
        label = sample.prompt_title or pid
        cls = "" if idx != 0 else ""
        parts.append(
            f'<button onclick="showSection(\'sec_{idx}\')" '
            f'class="{cls}">{_esc(label)}</button>'
        )
    parts.append("</nav>")

    # One section div per prompt -----------------------------------------
    for s_idx, pid in enumerate(prompt_ids):
        inner = grouped[pid]
        sec_display = "display:block;" if s_idx == 0 else "display:none;"
        parts.append(f'<div class="section" id="sec_{s_idx}" '
                      f'style="{sec_display}">')

        # Model tab bar for this section
        parts.append('<nav class="tabs" id="mtabs_' + str(s_idx) + '">')
        for m_idx, mk in enumerate(cols):
            parts.append(
                f'<button onclick="showModelTab(this,{s_idx},{m_idx})">'
                f'{_esc(mk)}</button>'
            )
        parts.append("</nav>")

        # Panes
        parts.append('<div class="iframe-wrap">')
        for m_idx, mk in enumerate(cols):
            r = inner.get(mk)
            prefix = _resolve_prefix(r) if r else pid
            fname = _artifact_filename(prefix, mk)
            fpath = artifacts_dir / fname
            rel_src = ("./" + fname) if fpath.exists() else ""

            pane_style = "display:block;" if m_idx == 0 else "display:none;"
            parts.append(
                f'<div class="pane" data-tab="{s_idx}_{m_idx}" '
                f'style="{pane_style}height:100%;">'
            )

            if rel_src:
                parts.append(f'<iframe src="{_esc_attr(rel_src)}"></iframe>')
            else:
                parts.append(
                    f'<div class="missing">Artifact not found: '
                    f'{_esc(fname)}<br/>'
                    f'(expected in {artifacts_dir.name}/)</div>'
                )
            parts.append("</div>")
        parts.append("</div>")  # iframe-wrap
        parts.append("</div>")  # section

    # Combined JS --------------------------------------------------------
    parts.append("""
<script>
var curSec=null;

function showSection(id){
  var secs=document.querySelectorAll('.section');
  for(var i=0;i<secs.length;i++){
    secs[i].style.display=(secs[i].id===id)?'block':'none';
  }
  curSec=id;
  // Reset to first model tab in the revealed section
  var mtabs=document.getElementById('mtabs_'+id.slice(4));
  if(mtabs && mtabs.firstElementChild){
    mtabs.firstElementChild.onclick();
  }
  // Highlight section button
  var sb=document.querySelectorAll('#section-tabs button');
  for(var j=0;j<sb.length;j++){sb[j].classList.remove('active');}
  event.currentTarget.classList.add('active');
}

function showModelTab(btn,sIdx,mIdx){
  var bar=btn.parentElement.children;
  for(var i=0;i<bar.length;i++){bar[i].classList.remove('active');}
  btn.classList.add('active');
  var panes=btn.closest('.section').querySelectorAll('.pane');
  for(var j=0;j<panes.length;j++){
    var d=panes[j].getAttribute('data-tab');
    panes[j].style.display=(d===sIdx+'_'+mIdx)?'block':'none';
  }
}

// Init: highlight first section & first model tab
document.addEventListener('DOMContentLoaded',function(){
  var st=document.getElementById('section-tabs');
  if(st&&st.firstElementChild){
    st.firstElementChild.classList.add('active');
    st.firstElementChild.onclick.call(st.firstElementChild);
  }
});
</script>""")

    parts.append("</body></html>")

    out_path.write_text("\n".join(parts))
    return out_path
