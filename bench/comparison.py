"""Side-by-side comparison reports for multi-model benchmark results."""

from __future__ import annotations

import html
from collections import OrderedDict
from pathlib import Path
from typing import Iterable

from .executor import SingleResult


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _esc(text: str) -> str:
    """HTML-escape arbitrary text."""
    return html.escape(text or "", quote=False)


def _esc_attr(text: str) -> str:
    """HTML-escape for attribute values."""
    return html.escape(text or "", quote=True)


def _fmt_latency(seconds: float) -> str:
    if seconds <= 0:
        return "-"
    return f"{seconds * 1000:.0f} ms"


def _fmt_tokens(prompt_tokens: int, completion_tokens: int) -> str:
    return f"{prompt_tokens}→{completion_tokens}"


def _fmt_tps(tps: float) -> str:
    return f"{tps:.1f}" if tps > 0 else "-"


def _fmt_grade(grade) -> str:
    if grade is None or grade == "":
        return "-"
    return str(grade)


def _get_grade(result: SingleResult):
    """Return ``grade`` if present on the result, else ``None``."""
    return getattr(result, "grade", None)


def _get_grade_details(result: SingleResult):
    return getattr(result, "grade_details", None)


def _resolve_prefix(result: SingleResult) -> str:
    """Best-effort artifact filename prefix from a result.

    Prefers ``file_prefix`` if the result carries it; falls back to
    ``prompt_id``.
    """
    fp = getattr(result, "file_prefix", None)
    return fp if fp else result.prompt_id


def _group_by_prompt(
    results: Iterable[SingleResult],
    model_keys: list[str] | None,
) -> "OrderedDict[str, OrderedDict[str, SingleResult]]":
    """Group results into ``{prompt_id: {model_key: SingleResult}}``.

    Preserves insertion order of prompts and models.  When *model_keys*
    is given, only those models are retained (and in that order).
    """
    grouped: OrderedDict[str, OrderedDict[str, SingleResult]] = (
        OrderedDict()
    )
    for r in results:
        if model_keys is not None and r.model_key not in model_keys:
            continue
        inner = grouped.setdefault(r.prompt_id, OrderedDict())
        inner[r.model_key] = r
    return grouped


def _ordered_model_keys(
    grouped: "OrderedDict[str, OrderedDict[str, SingleResult]]",
    model_keys: list[str] | None,
) -> list[str]:
    """Deterministic model-column order."""
    if model_keys is not None:
        return [k for k in model_keys if any(k in d for d in grouped.values())]
    seen: list[str] = []
    for inner in grouped.values():
        for k in inner:
            if k not in seen:
                seen.append(k)
    return seen


# ---------------------------------------------------------------------------
# Public API – Markdown comparison
# ---------------------------------------------------------------------------

def write_comparison_markdown(
    results: list[SingleResult],
    out_path: Path,
    model_keys: list[str] | None = None,
) -> Path:
    """Generate a Markdown file with side-by-side model comparisons.

    For each ``prompt_id``, responses from different models are laid out in
    adjacent columns using an inline HTML ``<table>`` (pipe-tables are too
    rigid for long-form text).  Beneath each response cell a metrics row
    reports latency, tokens, throughput, and grade.

    Parameters
    ----------
    results
        Flat list of :class:`SingleResult` objects from the executor.
    out_path
        Destination ``.md`` file path.
    model_keys
        Optional whitelist of model keys to include.  When ``None`` every
        model appearing in *results* is shown.
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)

    grouped = _group_by_prompt(results, model_keys)
    cols = _ordered_model_keys(grouped, model_keys)

    parts: list[str] = []

    # Header ---------------------------------------------------------------
    parts.append("# Side-by-Side Comparison\n")
    parts.append("> Generated by bench comparison module\n")

    if not grouped:
        parts.append("\n_No results to compare._\n")
        out_path.write_text("\n".join(parts))
        return out_path

    # One section per prompt ----------------------------------------------
    for prompt_id, inner in grouped.items():
        sample = next(iter(inner.values()))
        title = sample.prompt_title or prompt_id
        parts.append(f"\n---\n\n## {title}")
        parts.append(f"`{prompt_id}` · category={sample.category} "
                     f"· difficulty={sample.difficulty}\n")

        if not cols:
            parts.append("_No matching results._\n")
            continue

        # ---- Response row -------------------------------------------------
        col_width = max(220, int(900 / max(len(cols), 1)))

        tbl: list[str] = []
        tbl.append('<table border="1" cellpadding="8" '
                    'cellspacing="0" style="border-collapse:collapse;'
                    f'width:{col_width * len(cols)}px;">')

        # Header row
        tbl.append("<thead><tr>")
        for mk in cols:
            tbl.append(f"<th>{_esc(mk)}</th>")
        tbl.append("</tr></thead>")

        # Body – response row
        tbl.append("<tbody>")
        tbl.append("<tr>")
        for mk in cols:
            r = inner.get(mk)
            if r is None:
                tbl.append("<td valign=\"top\"><em>(no result)</em></td>")
                continue
            if r.error:
                tbl.append(
                    "<td valign=\"top\">"
                    f'<strong style="color:red">ERROR</strong>'
                    f"<br/><code>{_esc(r.error[:300])}</code>"
                    "</td>"
                )
            else:
                tbl.append(
                    "<td valign=\"top\">"
                    f'<pre style="white-space:pre-wrap;word-wrap:break-word;'
                    f'margin:0;font-size:0.85em;line-height:1.4;">'
                    f'{_esc(r.response_text)}'
                    "</pre></td>"
                )
        tbl.append("</tr>")

        # Metrics row
        tbl.append("<tr>")
        for mk in cols:
            r = inner.get(mk)
            if r is None:
                tbl.append("<td valign=\"top\"></td>")
                continue
            metric_cells = [
                f"<b>Latency:</b> {_fmt_latency(r.total_time)}",
                f"<b>Tokens:</b> {_fmt_tokens(r.prompt_tokens, r.completion_tokens)}",
                f"<b>Tok/s:</b> {_fmt_tps(r.tokens_per_second)}",
                f"<b>Grade:</b> {_fmt_grade(_get_grade(r))}",
            ]
            gd = _get_grade_details(r)
            if gd:
                metric_cells.append(f"<details><summary>Details</summary>"
                                   f"{_esc(str(gd))}</details>")
            tbl.append(
                "<td valign=\"top\" style=\"font-size:0.85em;"
                "border-top:none;\">"
                + "<br/>".join(metric_cells)
                + "</td>"
            )
        tbl.append("</tr>")

        tbl.append("</tbody></table>\n")
        parts.append("\n".join(tbl))

    out_path.write_text("\n".join(parts))
    return out_path


